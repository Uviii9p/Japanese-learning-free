/**
 * Searches Jisho.org Japanese Dictionary API (100% free, public, no key)
 */
async function searchJisho(keyword: string) {
  try {
    const res = await fetch(`https://jisho.org/api/v1/search/words?keyword=${encodeURIComponent(keyword)}`, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)',
        'Accept': 'application/json'
      }
    });
    if (!res.ok) return null;
    const data = await res.json();
    return data?.data?.[0] || null;
  } catch {
    return null;
  }
}

/**
 * Parses [CORRECTION] blocks generated by LLMs into structured correction objects
 */
function parseCorrectionBlock(text: string): { cleanText: string; correction?: { incorrect: string; correct: string; explanation: string } } {
  const match = text.match(/\[CORRECTION\]\s*Incorrect:\s*([^\n]+)\s*Correct:\s*([^\n]+)\s*Explanation:\s*([^\]]+)\s*\[\/CORRECTION\]/i);
  if (!match) return { cleanText: text };

  const cleanText = text.replace(/\[CORRECTION\][\s\S]*?\[\/CORRECTION\]/i, '').trim();
  return {
    cleanText,
    correction: {
      incorrect: match[1].trim(),
      correct: match[2].trim(),
      explanation: match[3].trim()
    }
  };
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { messages = [], provider = 'auto', apiKey = '' } = body;

    const lastMessage = messages[messages.length - 1];
    const userPrompt = lastMessage?.content || '';

    // Determine active API key (Client passed or Environment variable)
    const geminiKey = apiKey?.startsWith('AIza') ? apiKey : (process.env.GEMINI_API_KEY || (provider === 'gemini' ? apiKey : ''));
    const groqKey = apiKey?.startsWith('gsk_') ? apiKey : (process.env.GROQ_API_KEY || (provider === 'groq' ? apiKey : ''));
    const openRouterKey = apiKey?.startsWith('sk-or-') ? apiKey : (process.env.OPENROUTER_API_KEY || (provider === 'openrouter' ? apiKey : ''));

    // Check if user specifically asked for a dictionary lookup (Jisho)
    const dictMatch = userPrompt.match(/(?:what does|meaning of|define|search|lookup)\s+["']?([a-zA-Z\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FAF]+)["']?/i);
    let jishoInfo = '';
    if (dictMatch?.[1]) {
      const jResult = await searchJisho(dictMatch[1]);
      if (jResult) {
        const word = jResult.japanese?.[0]?.word || jResult.japanese?.[0]?.reading || dictMatch[1];
        const reading = jResult.japanese?.[0]?.reading || '';
        const defs = jResult.senses?.[0]?.english_definitions?.slice(0, 3)?.join(', ') || '';
        const jlpt = jResult.jlpt?.[0] ? ` [${jResult.jlpt[0].toUpperCase()}]` : '';
        jishoInfo = `\n\n📖 **Jisho Dictionary Entry:** **${word}** ${reading ? `(${reading})` : ''}${jlpt} — *${defs}*`;
      }
    }

    // Try Cloud AI Provider if key is present
    let rawResponse = '';
    let usedProvider = 'sensei-engine';

    if (geminiKey) {
      try {
        rawResponse = await callGemini(messages, geminiKey);
        usedProvider = 'Google Gemini (Free Tier)';
      } catch (err: unknown) {
        console.warn('Gemini failed, falling back:', (err as Error).message);
      }
    } else if (groqKey) {
      try {
        rawResponse = await callGroq(messages, groqKey);
        usedProvider = 'Groq Llama 3.3 70B (Free)';
      } catch (err: unknown) {
        console.warn('Groq failed, falling back:', (err as Error).message);
      }
    } else if (openRouterKey) {
      try {
        rawResponse = await callOpenRouter(messages, openRouterKey);
        usedProvider = 'OpenRouter Free AI';
      } catch (err: unknown) {
        console.warn('OpenRouter failed, falling back:', (err as Error).message);
      }
    }

    // If Cloud AI succeeded:
    if (rawResponse) {
      const { cleanText, correction } = parseCorrectionBlock(rawResponse);
      return NextResponse.json({
        text: cleanText + jishoInfo,
        correction,
        provider: usedProvider,
        success: true
      });
    }

    // Fallback: Built-in Sensei Linguistic Engine
    const senseiResult = querySenseiEngine(userPrompt);
    return NextResponse.json({
      text: senseiResult.text + jishoInfo,
      correction: senseiResult.correction,
      suggestions: senseiResult.suggestions,
      japaneseAudio: senseiResult.japaneseAudio,
      provider: 'Sensei AI Engine (Free Built-in)',
      success: true
    });

  } catch (err: unknown) {
    console.error('Tutor API error:', err);
    return NextResponse.json(
      { error: (err as Error).message || 'Failed to process tutor query' },
      { status: 500 }
    );
  }
}
