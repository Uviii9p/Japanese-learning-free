import { NextRequest, NextResponse } from 'next/server';
import { querySenseiEngine } from '@/lib/senseiEngine';

interface ChatMessage {
  role: 'user' | 'assistant' | 'system';
  content: string;
}

const SYSTEM_PROMPT = `You are Sensei (先生), an expert, kind, and encouraging Japanese language teacher for students from absolute beginners to JLPT N1.
Your goals:
1. Always be patient, warm, and motivating.
2. If the user writes a Japanese sentence with any grammar or vocabulary mistakes, provide a clear structured correction:
[CORRECTION]
Incorrect: <the incorrect Japanese sentence/word>
Correct: <the corrected Japanese sentence with furigana or kanji>
Explanation: <friendly, clear explanation of why and what rule applies>
[/CORRECTION]
3. When introducing Japanese words, provide: Japanese (Kanji/Kana) + Romaji + English translation.
4. Keep explanations concise, practical, and easy to understand.
5. If the user asks general conversational questions ("how are you", "hi"), answer naturally in Japanese with English translation and romaji, and invite them to practice Japanese!`;

/**
 * Calls Google Gemini Free API (1.5 Flash / 2.0 Flash)
 */
async function callGemini(messages: ChatMessage[], apiKey: string): Promise<string> {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

  // Build Gemini contents
  const contents = messages
    .filter(m => m.role !== 'system')
    .map(m => ({
      role: m.role === 'assistant' ? 'model' : 'user',
      parts: [{ text: m.content }]
    }));

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents,
      systemInstruction: {
        parts: [{ text: SYSTEM_PROMPT }]
      },
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 1000,
      }
    })
  });

  if (!res.ok) {
    const errorData = await res.text();
    throw new Error(`Gemini API error (${res.status}): ${errorData.slice(0, 150)}`);
  }

  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error('No response from Gemini API');
  return text;
}

/**
 * Calls Groq Free API (Llama 3.3 70B)
 */
async function callGroq(messages: ChatMessage[], apiKey: string): Promise<string> {
  const url = 'https://api.groq.com/openai/v1/chat/completions';

  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model: 'llama-3.3-70b-versatile',
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        ...messages
      ],
      temperature: 0.7,
      max_tokens: 1000
    })
  });

  if (!res.ok) {
    const errorData = await res.text();
    throw new Error(`Groq API error (${res.status}): ${errorData.slice(0, 150)}`);
  }

  const data = await res.json();
  const text = data?.choices?.[0]?.message?.content;
  if (!text) throw new Error('No response from Groq API');
  return text;
}

